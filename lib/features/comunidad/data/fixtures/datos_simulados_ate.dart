import '../../domain/entities/vecino_ranking.dart';

class VecinoSimuladoSeed {
  const VecinoSimuladoSeed({
    required this.uid,
    required this.nombre,
    required this.iniciales,
    required this.distrito,
    required this.provincia,
    required this.departamento,
    required this.telefono,
    required this.bio,
    required this.xpTotal,
    required this.xpPeriodo,
    required this.nivel,
    required this.estrellas,
    required this.favoresCompletados,
    required this.eventosAsistidos,
    required this.reconocimientos,
    required this.rachaSemanal,
    required this.tendencia,
    required this.insignias,
    required this.herramientas,
  });

  final String uid;
  final String nombre;
  final String iniciales;
  final String distrito;
  final String provincia;
  final String departamento;
  final String telefono;
  final String bio;
  final int xpTotal;
  final int xpPeriodo;
  final int nivel;
  final int estrellas;
  final int favoresCompletados;
  final int eventosAsistidos;
  final int reconocimientos;
  final int rachaSemanal;
  final TendenciaRanking tendencia;
  final List<String> insignias;
  final int herramientas;

  VecinoRanking toRanking(int posicion) => VecinoRanking(
    uid: uid,
    nombre: nombre,
    iniciales: iniciales,
    distrito: distrito,
    xpPeriodo: xpPeriodo,
    posicion: posicion,
    nivel: nivel,
    bio: bio,
    insignias: insignias,
    favoresCompletados: favoresCompletados,
    estrellas: estrellas,
    eventosAsistidos: eventosAsistidos,
    reconocimientos: reconocimientos,
    rachaSemanal: rachaSemanal,
    tendencia: tendencia,
    xpTotal: xpTotal,
  );

  Map<String, dynamic> toUserMap() => {
    'name': nombre,
    'firstName': nombre.split(' ').first,
    'lastName': nombre.split(' ').skip(1).join(' '),
    'phoneNumber': telefono,
    'bio': bio,
    'department': departamento,
    'province': provincia,
    'district': distrito,
    'xp': xpTotal,
    'weeklyXp': xpPeriodo,
    'level': nivel,
    'stars': estrellas,
    'favors': favoresCompletados,
    'tools': herramientas,
    'badges': insignias,
    'stats': {
      'favoresCompletados': favoresCompletados,
      'eventosAsistidos': eventosAsistidos,
      'reconocimientos': reconocimientos,
      'rachaSemanal': rachaSemanal,
    },
    'tendencia': tendencia.name,
    'petHunger': 0.0,
  };

  Map<String, dynamic> toRankingMap(int posicion) => {
    'uid': uid,
    'nombre': nombre,
    'iniciales': iniciales,
    'distrito': distrito,
    'xpPeriodo': xpPeriodo,
    'posicion': posicion,
    'nivel': nivel,
    'bio': bio,
    'insignias': insignias,
    'favoresCompletados': favoresCompletados,
    'estrellas': estrellas,
    'eventosAsistidos': eventosAsistidos,
    'reconocimientos': reconocimientos,
    'rachaSemanal': rachaSemanal,
    'tendencia': tendencia.name,
    'xpTotal': xpTotal,
  };
}

